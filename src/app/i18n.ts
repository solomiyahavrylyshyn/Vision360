const TRANSLATIONS: Record<string, Dict> = { English: en, Spanish: es, Portuguese: pt, French: fr, German: de, Danish: da, Dutch: nl, Polish: pl };

/** Translate a key for a language, falling back to English then the raw key/fallback. */
export function translate(language: string, key: string, fallback?: string): string {
  return TRANSLATIONS[language]?.[key] ?? en[key] ?? fallback ?? key;
}

/** Reactive translator hook — re-renders when the Localization language changes. */
export function useT() {
  const settings = useSyncExternalStore(regionalSettingsStore.subscribe, regionalSettingsStore.getSnapshot);
  const language = settings.language;
  const t = (key: string, fallback?: string) => translate(language, key, fallback);
  return { t, language, langCode: LANG_CODES[language] ?? "en" };
}
